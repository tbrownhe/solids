import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {chromium,expect} from '@playwright/test'
const baseURL=process.env.STUDIO_URL ?? 'http://127.0.0.1:8081'
const artifacts=new URL('../../artifacts/ui-pass/',import.meta.url).pathname
await mkdir(artifacts,{recursive:true})
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
try {
  const context=await browser.newContext({baseURL,viewport:{width:1280,height:800},reducedMotion:'reduce'})
  const page=await context.newPage(),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
  await page.goto('/')
  const download=page.getByRole('button',{name:'Download PDF',exact:true})
  await expect(download).toBeEnabled();await expect(page.locator('.solid-canvas canvas')).toBeVisible()
  await page.getByRole('link',{name:'Start designing',exact:true}).click()
  async function inViewport(selector) {
    const r=await page.locator(selector).boundingBox();assert(r && r.y>=0 && r.y+r.height<=800.5,`${selector} must fit in the laptop workspace: ${JSON.stringify(r)}`)
  }
  await inViewport('.assembled-size');await inViewport('.viewport');await inViewport('.workspace-export')
  const modelHeight=(await page.locator('.viewport').boundingBox()).height
  await page.getByRole('button',{name:'Expand model',exact:true}).click()
  assert((await page.locator('.viewport').boundingBox()).height>modelHeight+100)
  await page.getByRole('button',{name:'Show design details',exact:true}).click()
  await expect(page.locator('#preset')).toHaveCount(0)
  await page.locator('#edge').fill('150');await expect(download).toBeEnabled()
  await page.locator('#thickness').fill('7.5');await expect(download).toBeEnabled()
  await page.locator('#shrinkage').fill('10');await expect(download).toBeEnabled()
  await page.getByRole('button',{name:'Print settings',exact:true}).click()
  await page.locator('#paper').selectOption('a4')
  await page.locator('.advanced-print summary').click();await page.locator('#precision').selectOption('3')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button',{name:'Print settings',exact:true})).toBeFocused()
  await page.locator('#solid').selectOption('cube')
  await expect(page.locator('#preset')).toHaveValue('')
  await expect(page.locator('#preset option')).toHaveText(['Original','Recess one face','Recess all faces','Outward pyramids'])
  await expect(page.locator('#edge')).toHaveValue('150');await expect(page.locator('#thickness')).toHaveValue('7.5');await expect(page.locator('#shrinkage')).toHaveValue('10')
  await page.locator('#preset').selectOption('stellated-cube');await expect(download).toBeEnabled()
  await expect(page.locator('#solid')).toHaveValue('cube')
  await expect(page.getByLabel('Point height fired mm',{exact:true})).toBeVisible()
  const before=await page.locator('.viewport').boundingBox()
  await page.getByRole('button',{name:/^Edit individual faces/}).click()
  await expect(page.locator('.selected-face-editor')).toBeVisible()
  const after=await page.locator('.viewport').boundingBox()
  assert.equal(after.height,before.height);assert.equal(after.y,before.y)
  await page.locator('#face-mode').selectOption('flat');await expect(download).toBeEnabled()
  await expect(page.locator('#preset')).toHaveValue('custom')
  await expect(page.locator('.selection-meta')).toContainText('F001 · Template')
  await inViewport('.workspace-export')
  await page.getByRole('button',{name:'Show dimensions',exact:true}).click()
  await expect(page.locator('.dimension-label')).toHaveCount(3)
  await expect(page.locator('.dimension-label').first()).toContainText('W ')
  await expect.poll(()=>page.evaluate(()=>{const host=document.querySelector('.solid-canvas').getBoundingClientRect();const labels=[...document.querySelectorAll('.dimension-label')].map(el=>el.getBoundingClientRect());return labels.every((r,i)=>r.x>=host.x && r.y>=host.y && r.right<=host.right && r.bottom<=host.bottom && labels.slice(i+1).every(q=>r.right<=q.left || q.right<=r.left || r.bottom<=q.top || q.bottom<=r.top))})).toBe(true)
  await page.getByRole('button',{name:'Show dimensions',exact:true}).click()
  await expect(page.locator('.dimension-label')).toHaveCount(0)
  await page.getByRole('tab',{name:'Joint settings',exact:true}).click()
  await page.getByRole('tab',{name:'Joint settings',exact:true}).press('ArrowRight')
  await expect(page.locator('#inspector-tab-fitting')).toBeFocused()
  await expect(page.locator('#inspector-panel-fitting')).toBeVisible()
  await page.getByRole('button',{name:'Next fitting corner'}).click()
  await expect(page.locator('.fitting-heading')).toContainText('Corner 2 of 4')
  await page.locator('#solid').selectOption('dodecahedron');await expect(download).toBeEnabled()
  await expect(page.locator('#preset option')).toHaveText(['Original','Outward pyramids'])
  await expect(page.locator('#preset')).toHaveValue('')
  await expect(page.locator('#edge')).toHaveValue('150');await expect(page.locator('#shrinkage')).toHaveValue('10')
  await page.getByRole('button',{name:'Print settings',exact:true}).click()
  await expect(page.locator('#paper')).toHaveValue('a4');await expect(page.locator('#precision')).toHaveValue('3')
  for(let i=0;i<8;i++){await page.keyboard.press('Tab');assert(await page.evaluate(()=>!!document.activeElement?.closest('.print-dialog')),'Modal focus must stay inside print settings')}
  await page.keyboard.press('Escape')
  await page.locator('#solid').selectOption('truncated-octahedron');await expect(download).toBeEnabled()
  await expect(page.locator('#preset')).toHaveCount(0)
  await expect(page.getByRole('button',{name:/^Edit individual faces/})).toHaveCount(0)
  await page.locator('.workspace').screenshot({path:`${artifacts}workspace-laptop.png`})
  assert.deepEqual(errors,[])
  await context.close()
  for(const [width,height] of [[820,1180],[390,844],[320,740]]) {
    const ctx=await browser.newContext({baseURL,viewport:{width,height},reducedMotion:'reduce',hasTouch:true})
    const p=await ctx.newPage();p.on('pageerror',e=>errors.push(e.message));await p.goto('/')
    await expect(p.getByRole('button',{name:'Download PDF',exact:true})).toBeEnabled()
    await p.getByRole('link',{name:'Start designing',exact:true}).click()
    const viewer=await p.locator('.viewport').boundingBox(),exportBar=await p.locator('.workspace-export').boundingBox()
    assert(viewer.y>=0 && viewer.y+viewer.height<height,`Model must be visible before controls at ${width}px`)
    assert(exportBar.y>=0 && exportBar.y+exportBar.height<=height+.5,`Export must stay visible at ${width}px`)
    await p.getByRole('button',{name:'Controls',exact:true}).click()
    const sheet=p.getByRole('dialog',{name:'Shape, size & clay'})
    await expect(sheet).toBeVisible()
    await expect(p.locator('#solid')).toHaveCount(1)
    await p.locator('#solid').selectOption('cube');await p.locator('#preset').selectOption('stellated-cube')
    await expect(p.locator('#solid')).toHaveValue('cube')
    await p.locator('#edge').fill('135')
    await p.keyboard.press('Escape');await expect(sheet).not.toBeVisible()
    await expect(p.getByRole('button',{name:'Controls',exact:true})).toBeFocused()
    await expect(p.getByRole('button',{name:'Download PDF',exact:true})).toBeEnabled()
    await expect(p.locator('.mobile-shape-summary')).toContainText('Cube')
    assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true)
    await p.locator('.workspace').screenshot({path:`${artifacts}workspace-${width}.png`})
    await p.getByRole('button',{name:'Controls',exact:true}).click()
    await expect(p.locator('#edge')).toHaveValue('135')
    if(width===820) {
      await p.setViewportSize({width:1280,height:800})
      await expect(p.getByRole('dialog',{name:'Shape, size & clay'})).toHaveCount(0)
      await expect(p.locator('.workspace>.settings')).toBeVisible()
      await expect(p.locator('#edge')).toHaveValue('135')
      await expect(p.locator('#solid')).toHaveCount(1)
    }
    await ctx.close()
  }
  assert.deepEqual(errors,[])
  console.log('Workspace QA passed: laptop bounds, dependent recipes, preserved size/clay/print values, contextual editing, dimension overlay, keyboard tabs, fitting navigation, modal focus/escape, responsive controls and mobile export.')
} finally {await browser.close()}
