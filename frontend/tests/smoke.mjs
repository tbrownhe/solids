import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { chromium, expect } from '@playwright/test'

const baseURL = process.env.STUDIO_URL ?? 'http://127.0.0.1:8081'
const artifacts = new URL('../../artifacts/browser/', import.meta.url).pathname
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
try {
  const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1050 }, acceptDownloads: true })
  const page = await context.newPage()
  const errors = [], externalRequests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith(baseURL) && !request.url().startsWith('blob:') && !request.url().startsWith('data:')) externalRequests.push(request.url()) })
  await page.goto('/')
  const downloadButton = page.getByRole('button', { name: 'Download templates' })
  await expect(downloadButton).toBeEnabled()
  assert.equal(await page.locator('#solid option').count(), 18)
  assert.equal(await page.locator('.template-card').count(), 3)
  for (const [i, quantity] of [8, 6, 12].entries()) {
    await expect(page.locator('.template-card .panel-svg').nth(i)).toContainText(`MAKE ${quantity}`)
  }
  await expect(page.locator('.download-note')).toContainText('4 sheets')
  await expect(page.locator('.solid-canvas canvas')).toBeVisible()
  await expect(page.getByText('72.37', { exact: false }).first()).toBeVisible()
  await page.screenshot({ path: `${artifacts}studio-desktop.png`, fullPage: true })
  await page.getByRole('tab', { name: 'Flat panels' }).click()
  await expect(page.locator('.flat-view .panel-svg')).toBeVisible()
  await page.getByRole('button', { name: 'Inspect template B', exact: true }).click()
  await expect(page.locator('.viewport-tag')).toHaveText('TEMPLATE B / INTERIOR FACE UP')
  await page.locator('#shrinkage').fill('10')
  await expect(page.locator('.working-edge strong')).toHaveText('133.33 mm')
  await expect(downloadButton).toBeEnabled()
  await page.reload()
  await expect(page.locator('#shrinkage')).toHaveValue('10')
  await expect(downloadButton).toBeEnabled()
  await page.locator('#solid').selectOption('truncated-octahedron')
  await expect(page.locator('.viewport-name > span')).toHaveText('Truncated octahedron')
  assert.equal(await page.locator('.template-card').count(), 2)
  await page.locator('#paper').selectOption('a3')
  await expect(page.locator('.download-note')).toContainText('3 sheets')
  await page.locator('#precision').selectOption('4')
  await expect(page.locator('.joint-types')).toContainText('62.6322')
  await page.locator('.joint').first().click()
  await expect(page.locator('.inspector')).toContainText('interior dihedral')
  const pdfDownload = page.waitForEvent('download')
  await downloadButton.click()
  await (await pdfDownload).saveAs(`${artifacts}downloaded-templates.pdf`)
  assert.equal((await readFile(`${artifacts}downloaded-templates.pdf`)).subarray(0, 4).toString(), '%PDF')
  const svgDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download template A as SVG' }).click()
  await (await svgDownload).saveAs(`${artifacts}downloaded-panel.svg`)
  assert.match(await readFile(`${artifacts}downloaded-panel.svg`, 'utf8'), /EXTERIOR FACE DOWN for cutting AND beveling/)
  await page.locator('#edge').fill('0')
  await expect(page.getByRole('alert').first()).toBeVisible()
  await expect(downloadButton).toBeDisabled()
  await page.getByRole('button', { name: 'Reset to studio defaults' }).click()
  await expect(page.locator('.working-edge strong')).toHaveText('120.00 mm')
  await expect(downloadButton).toBeEnabled()
  await page.getByRole('button', { name: 'The cutting guide', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog')).toContainText('Keep the exterior face down and the interior face up throughout cutting and beveling.')
  await expect(page.getByRole('dialog').getByRole('link', { name: /Precision Beveler/ })).toHaveAttribute('href', /etsy.com\/listing\/4466016418/)
  await page.getByRole('dialog').screenshot({ path: `${artifacts}cutting-guide.png` })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  assert.deepEqual(errors, [])
  assert.deepEqual(externalRequests, [], 'Studio must not require third-party runtime requests')
  await context.close()

  const mobile = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const mobilePage = await mobile.newPage()
  await mobilePage.goto('/')
  await expect(mobilePage.getByRole('button', { name: 'Download templates' })).toBeEnabled()
  const noOverflow = await mobilePage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
  assert.equal(noOverflow, true, 'Mobile layout must not overflow horizontally')
  await mobilePage.screenshot({ path: `${artifacts}studio-mobile.png`, fullPage: true })
  await mobile.close()
  console.log('Browser QA passed: 18 solids, previews, parameters, persistence, edge inspector, PDF/SVG downloads, invalid inputs, guide, mobile layout; no external runtime requests or JS errors.')
} finally { await browser.close() }
