import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { chromium, expect } from '@playwright/test'

const baseURL=process.env.STUDIO_URL ?? 'http://127.0.0.1:8081'
const artifacts=new URL('../../artifacts/browser/',import.meta.url).pathname
await mkdir(artifacts,{recursive:true})
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
try {
  const context=await browser.newContext({baseURL,viewport:{width:1440,height:1050},acceptDownloads:true})
  const page=await context.newPage()
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  const download=page.getByRole('button',{name:'Download templates',exact:true})
  await expect(download).toBeEnabled()
  await page.locator('#preset').selectOption('excavated-cube-single')
  await expect(page.locator('.viewport-name > span')).toHaveText('Cube · one recessed face')
  await expect(page.locator('.settings > .field-hint').first()).toContainText('9 faces · 16 edges')
  await expect(page.locator('.joint-types')).toContainText('concave')
  await expect(page.locator('.joint-types')).toContainText('OUT / exterior up')
  await expect(download).toBeEnabled()
  await page.screenshot({path:`${artifacts}phase2-desktop.png`,fullPage:true})
  await page.getByRole('tab',{name:'Flat panels'}).click()
  await expect(page.locator('.flat-view .panel-svg')).toContainText('OUT')
  await page.getByRole('button',{name:'View exterior',exact:true}).click()
  await expect(page.locator('.viewport-tag')).toContainText('EXTERIOR FACE UP')
  await page.getByRole('button',{name:'View interior',exact:true}).click()
  await expect(page.locator('.viewport-tag')).toContainText('INTERIOR FACE UP')
  await page.screenshot({path:`${artifacts}phase2-flat.png`,fullPage:true})
  await page.getByRole('tab',{name:'3D solid'}).click()
  const canvas=page.locator('.solid-canvas canvas')
  const rect=await canvas.boundingBox()
  for (const x of [.54,.47,.6,.4]) {
    await page.mouse.click(rect.x+rect.width*x,rect.y+rect.height*.52)
    if (await page.locator('.face-editor').evaluate(el=>el.open)) break
  }
  await expect(page.locator('.face-editor')).toHaveAttribute('open','')
  await page.locator('#face-id').selectOption('F001')
  await page.locator('#face-mode').selectOption('outward')
  await expect(page.locator('#preset')).toHaveValue('')
  await expect(download).toBeEnabled()
  await page.locator('#face-offset').fill('12')
  await expect(page.locator('#face-offset')).toHaveValue('12')
  await expect(download).toBeEnabled()
  await page.getByRole('button',{name:'Apply to all square faces',exact:true}).click()
  await expect(page.locator('.settings > .field-hint').first()).toContainText('24 faces')
  await expect(download).toBeEnabled()
  await page.getByRole('button',{name:'Reset transformations',exact:true}).click()
  await expect(page.locator('.settings > .field-hint').first()).toContainText('6 faces')
  await expect(download).toBeEnabled()
  await page.locator('#preset').selectOption('excavated-cube')
  await expect(page.locator('.viewport-name > span')).toHaveText('Excavated cube')
  await expect(download).toBeEnabled()
  await expect(page.locator('.template-card .panel-svg')).toContainText('MAKE 24')
  let next=page.waitForEvent('download')
  await page.getByRole('button',{name:'Save project',exact:true}).click()
  const project=await next
  await project.saveAs(`${artifacts}excavated-cube.solids.json`)
  const saved=JSON.parse(await readFile(`${artifacts}excavated-cube.solids.json`,'utf8'))
  assert.equal(saved.version,2)
  assert.equal(saved.geometry_version,2)
  assert.equal(saved.parameters.preset_id,'excavated-cube')
  const legacy={solid_id:'cube',edge_length_mm:120,thickness_mm:6,shrinkage_percent:0,page_format:'letter',angle_precision:2}
  await page.locator('input[type=file]').setInputFiles({name:'legacy.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(legacy))})
  await expect(page.locator('.settings > .field-hint').first()).toContainText('6 faces')
  await page.locator('input[type=file]').setInputFiles(`${artifacts}excavated-cube.solids.json`)
  await expect(page.locator('.viewport-name > span')).toHaveText('Excavated cube')
  await expect(download).toBeEnabled()
  await page.reload()
  await expect(page.locator('#preset')).toHaveValue('excavated-cube')
  await expect(download).toBeEnabled()
  next=page.waitForEvent('download');await download.click()
  await (await next).saveAs(`${artifacts}excavated-cube.pdf`)
  assert.equal((await readFile(`${artifacts}excavated-cube.pdf`)).subarray(0,4).toString(),'%PDF')
  next=page.waitForEvent('download');await page.getByRole('button',{name:'Download 60° test coupons',exact:true}).click()
  await (await next).saveAs(`${artifacts}calibration-coupons.pdf`)
  next=page.waitForEvent('download');await page.getByRole('button',{name:'Download template A as SVG'}).click()
  await (await next).saveAs(`${artifacts}excavated-panel.svg`)
  assert.match(await readFile(`${artifacts}excavated-panel.svg`,'utf8'),/OUT/)
  await page.getByRole('button',{name:'The cutting guide',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('Mixed panels need cuts from both sides.')
  await page.getByRole('dialog').screenshot({path:`${artifacts}phase2-guide.png`})
  await page.keyboard.press('Escape')
  await page.locator('#apex-offset').fill('61')
  await expect(page.getByRole('alert').first()).toContainText('center')
  await expect(download).toBeDisabled()
  await page.locator('#apex-offset').fill('20')
  await expect(download).toBeEnabled()
  await page.locator('#preset').selectOption('excavated-tetrahedron')
  await expect(page.locator('.viewport-name > span')).toHaveText('Excavated tetrahedron')
  await expect(page.locator('#apex-offset')).toHaveValue('8')
  await expect(download).toBeEnabled()
  const unsafe={...legacy,solid_id:'rhombicuboctahedron',face_transforms:{F009:{mode:'inward',offset_mm:12}}}
  await page.locator('input[type=file]').setInputFiles({name:'corner-relief.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(unsafe))})
  await expect(page.locator('.settings > .field-hint').first()).toContainText('29 faces')
  await expect(page.getByRole('alert').first()).toContainText('overlap')
  await expect(download).toBeDisabled()
  await page.getByRole('button',{name:'Reset to studio defaults'}).click()
  await expect(download).toBeEnabled()
  assert.deepEqual(errors,[])
  await context.close()
  const mobile=await browser.newContext({baseURL,viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  const p=await mobile.newPage();await p.goto('/')
  await expect(p.getByRole('button',{name:'Download templates',exact:true})).toBeEnabled()
  await p.locator('#preset').selectOption('excavated-cube')
  await expect(p.getByRole('button',{name:'Download templates',exact:true})).toBeEnabled()
  assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true)
  await p.screenshot({path:`${artifacts}phase2-mobile.png`,fullPage:true})
  await mobile.close()
  console.log('Phase 2 browser QA passed: presets, 3D face selection, individual/equivalent transforms, front/back, reset, legacy and v2 save/load, persistence, assembly PDF, SVG, coupons, rejection of unsafe geometry, mobile.')
} finally {await browser.close()}
